# Постановка задачи

Две фирмы производят взаимозаменяемые товары в одной нише.

- $M_0^1 = 3.9$, $M_0^2 = 2.9$
- $p_{cr} = 25$, $N = 39$, $q = 1$
- $\tau_1 = 29$, $\tau_2 = 19$
- $\tilde{p}_1 = 6.9$, $\tilde{p}_2 = 15.9$

# Случай 1: без соц.-псих. фактора

$$\frac{dM_1}{d\theta} = M_1 - \frac{b}{c_1}M_1M_2 - \frac{a_1}{c_1}M_1^2$$

![](image/case1.png)

# Случай 2: с соц.-псих. фактором

$$\frac{dM_1}{d\theta} = M_1 - \left(\frac{b}{c_1} + 0.00083\right)M_1M_2 - \frac{a_1}{c_1}M_1^2$$

